/** Home navigation and draft workflows in an isolated browser profile. Requires Vite. */
import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const base = process.env.HOME_TEST_URL ?? 'http://127.0.0.1:5173';
const output = 'node_modules/.cache/home-ui';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const checks = [], errors = [];
const check = (name, value) => { assert.ok(value, name); checks.push(name); };
try {
  const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  page.on('response', r => { if (r.status() >= 400) errors.push(`${r.status()} ${r.url()}`); });
  await page.goto(`${base}/?debug`);
  await page.waitForFunction(() => window.__ugc?.client.profile && window.__debug, null, { timeout: 90000 });
  await page.locator('#loading').waitFor({ state: 'detached', timeout: 90000 });
  if (await page.locator('.debug-panel').isVisible()) await page.keyboard.press('Backquote');
  const homeNav = page.locator('.ugc-nav-button').filter({ hasText: '家園' });
  const home = page.locator('.home-panel');
  await homeNav.click();
  check('home navigation opens the panel with expanded state', await homeNav.getAttribute('aria-expanded') === 'true');
  check('starter profile exposes only owned scenes', await home.locator('.ugc-home-scene-choice').count() === 1);
  check('unchanged configuration cannot be saved again', await home.getByRole('button', { name: '儲存設定', exact: true }).isDisabled());
  await page.keyboard.press('Escape');
  check('Escape clears active navigation state', await homeNav.getAttribute('aria-expanded') === 'false');
  await page.evaluate(() => window.__debug.unlockAll());
  await page.waitForFunction(() => window.__ugc.client.profile.scenes.length === 10);
  await page.evaluate(async () => {
    const { client, panels } = window.__ugc;
    await client.saveHome([21, 0, 20].map(sceneType => ({ sceneType, fishTypes: panels.home.defaultFish(sceneType) })));
    window.__debug.server.profile.profile.home.pending = 129414;
    window.__debug.server.profile.profile.home.totalEarned = 148820;
    window.__debug.server.home.sendIncome();
  });
  await page.waitForFunction(() => window.__ugc.client.income.pending >= 129414);
  await page.locator('.ui-toast').last().waitFor({ state: 'detached', timeout: 6000 });
  await page.locator('.ugc-topbar').screenshot({ path: `${output}/navigation.png` });
  await homeNav.click();
  await home.locator('img').evaluateAll(imgs => Promise.all(imgs.map(img => img.decode().catch(() => {}))));
  await page.screenshot({ path: `${output}/desktop.png` });
  check('all owned scenes available as keyboard-operable buttons', await home.locator('.ugc-home-scene-choice').count() === 10);
  check('selected scene is exposed through aria-pressed', await home.locator('.ugc-home-scene-choice[aria-pressed="true"]').count() === 1);
  const beforeClaim = await page.evaluate(() => window.__debug.server.profile.profile.money);
  await home.getByRole('button', { name: '領取收益', exact: true }).click();
  await page.waitForFunction(n => window.__debug.server.profile.profile.money >= n + 129414, beforeClaim);
  check('claim credits real server balance', await page.evaluate(n => window.__debug.server.profile.profile.money >= n + 129414, beforeClaim));
  await home.getByRole('button', { name: '場景：赤楓燈籠神社', exact: true }).click();
  check('scene choice marks draft dirty and offers save-and-decorate', await home.getByRole('button', { name: '儲存並裝潢', exact: true }).isVisible());
  await home.getByRole('button', { name: '取消一般龍', exact: true }).click();
  check('empty selection explains minimum dragon requirement', await home.locator('.ugc-home-inline-warn').isVisible());
  await home.getByRole('button', { name: '儲存設定', exact: true }).click();
  check('invalid draft stays open without saving', await page.evaluate(() => window.__ugc.panels.home.dirty && window.__ugc.client.profile.home.slots[0].sceneType === 21));
  await home.getByRole('button', { name: '一般龍全選', exact: true }).click();
  check('bulk selection obeys scene restrictions and excludes bosses', await page.evaluate(() => {
    const p = window.__ugc.panels.home, s = p.draft[p.selected];
    return JSON.stringify(s.fishTypes) === JSON.stringify(p.defaultFish(s.sceneType));
  }));
  const lastFish = home.locator('.ugc-home-fish-grid .ugc-pick[aria-disabled="false"]').last();
  await lastFish.scrollIntoViewIfNeeded();
  const editorScroll = await home.locator('.ugc-home-editor').evaluate(e => e.scrollTop);
  await lastFish.click();
  check('dragon selection preserves scroll position and keyboard focus', await home.locator('.ugc-home-editor').evaluate((e, before) => Math.abs(e.scrollTop - before) < 2 && !!document.activeElement?.getAttribute('data-fish-type'), editorScroll));
  const draft = await page.evaluate(() => window.__ugc.panels.home.draft);
  await page.keyboard.press('Escape'); await homeNav.click();
  check('closing and reopening retains unsaved draft', await page.evaluate(d => JSON.stringify(window.__ugc.panels.home.draft) === JSON.stringify(d), draft));
  await home.getByRole('button', { name: '復原變更', exact: true }).click();
  check('reset restores saved settings and clears dirty status', await page.evaluate(() => !window.__ugc.panels.home.dirty && window.__ugc.panels.home.draft[0].sceneType === 21));
  await home.getByRole('button', { name: '編輯第 3 格 月球', exact: true }).click();
  await home.getByRole('button', { name: '第 1 格刪除', exact: true }).click();
  check('deleting earlier slot keeps the same scene selected', await page.evaluate(() => { const p = window.__ugc.panels.home; return p.selected === 1 && p.draft[p.selected].sceneType === 20; }));
  await home.getByRole('button', { name: '第 2 格上移', exact: true }).click();
  check('reorder carries the selected scene with its dragons', await page.evaluate(() => { const p = window.__ugc.panels.home; return p.selected === 0 && p.draft[0].sceneType === 20; }));
  for (let i = 0; i < 6; i++) await home.getByRole('button', { name: '＋ 新增場景', exact: true }).click();
  check('slot limit disables add after eight scenes', await home.getByRole('button', { name: '＋ 新增場景', exact: true }).isDisabled());
  await home.getByRole('button', { name: '儲存設定', exact: true }).click();
  await page.waitForFunction(() => !window.__ugc.panels.home.dirty && !window.__ugc.panels.home.saving);
  check('save persists eight scenes through the server', await page.evaluate(() => window.__ugc.client.profile.home.slots.length === 8));
  check('server rejects a ninth scene and preserves the eight saved scenes', await page.evaluate(async () => {
    const client = window.__ugc.client, slots = client.profile.home.slots;
    return !(await client.saveHome([...slots, slots[0]])).ok && client.profile.home.slots.length === 8;
  }));
  await home.locator('.ugc-home-slots').evaluate(e => e.scrollTop = 0);
  check('compact list previews at least five complete scenes and keeps add above it', await home.evaluate(e => {
    const list = e.querySelector('.ugc-home-slots').getBoundingClientRect();
    const add = e.querySelector('.ugc-home-add').getBoundingClientRect();
    const visible = [...e.querySelectorAll('.ugc-home-slot')].filter(row => { const r = row.getBoundingClientRect(); return r.top >= list.top - 1 && r.bottom <= list.bottom + 1; });
    return visible.length >= 5 && add.bottom <= list.top;
  }));
  await page.locator('.ui-toast').last().waitFor({ state: 'detached', timeout: 6000 });
  await page.screenshot({ path: `${output}/compact-eight.png` });
  await home.getByRole('button', { name: '第 8 格刪除', exact: true }).click();
  await home.getByRole('button', { name: '儲存並裝潢', exact: true }).click();
  await page.waitForFunction(() => window.__ugc.decor.active);
  check('save-and-decorate saves before entering the editor', await page.evaluate(() => window.__ugc.client.profile.home.slots.length === 7 && !window.__ugc.panels.home.dirty));
  await page.getByRole('button', { name: '取消', exact: true }).click();
  await page.waitForFunction(() => !window.__ugc.decor.active);
  await homeNav.click();
  await page.locator('.ui-toast').last().waitFor({ state: 'detached', timeout: 6000 });
  for (const [name, width, height] of [['wide', 1900, 900], ['tablet', 1024, 768], ['portrait', 430, 780]]) {
    await page.setViewportSize({ width, height });
    await page.waitForTimeout(200);
    const bounds = await home.evaluate(e => {
      const rect = e.getBoundingClientRect(), footer = e.querySelector('.ugc-home-actions').getBoundingClientRect();
      const editor = e.querySelector('.ugc-home-editor');
      return { x: rect.x, y: rect.y, right: rect.right, bottom: rect.bottom, footerBottom: footer.bottom, overflow: editor.scrollWidth > editor.clientWidth + 2 };
    });
    check(`${name} panel and actions fit the viewport`, bounds.x >= 0 && bounds.y >= 0 && bounds.right <= width + 1 && bounds.bottom <= height + 1 && bounds.footerBottom <= height && !bounds.overflow);
    await page.screenshot({ path: `${output}/${name}.png` });
  }
  await page.setViewportSize({ width: 1600, height: 1000 });
  await page.keyboard.press('Escape');
  await page.locator('.ugc-nav-button').filter({ hasText: '魚卡' }).click();
  check('collection navigation still opens correctly', await page.evaluate(() => window.__ugc.panels.cards.panel.isOpen));
  await page.keyboard.press('Escape');
  await page.locator('.ugc-nav-button').filter({ hasText: '抽卡' }).click();
  check('gacha navigation still opens correctly', await page.evaluate(() => window.__ugc.panels.gacha.panel.isOpen));
  await page.keyboard.press('Escape');
  await page.reload();
  await page.waitForFunction(() => window.__ugc?.client.profile, null, { timeout: 90000 });
  check('saved rotation survives reload', await page.evaluate(() => window.__ugc.client.profile.home.slots.length === 7));
  check('no runtime, shader or missing asset errors', errors.length === 0);
  console.log(JSON.stringify({ checks, errors, screenshots: output }, null, 2));
} finally { await browser.close(); }
